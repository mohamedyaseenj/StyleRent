 // Host-added items are persisted to localStorage (mock mode: backend offline)
 // so they survive a page refresh. Only items flagged `custom` are stored —
 // seed catalogue entries are never duplicated.
try {
  if (typeof localStorage !== 'undefined') {
    const raw = localStorage.getItem('sr_custom_products')
    const customs = raw ? JSON.parse(raw) : []
    if (Array.isArray(customs)) {
      customs.forEach((item) => {
        if (
          item &&
          item.clothing_id &&
          !products.some((p) => Number(p.clothing_id) === Number(item.clothing_id))
        ) {
          products.unshift(item)
        }
      })
    }
  }
} catch {
  /* corrupt storage: start from seed catalogue only */
}

export const getProductById = (id) =>
  products.find((p) => p.clothing_id === Number(id))

export const getRelatedProducts = (product, limit = 4) => {
  const sameCategory = products.filter(
    (p) => p.category_id === product.category_id && p.clothing_id !== product.clothing_id,
  )
  const rest = products.filter(
    (p) =>
      p.category_id !== product.category_id && p.clothing_id !== product.clothing_id,
  )
  return [...sameCategory, ...rest].slice(0, limit)
}

